  if (pathname.startsWith('/admission/our-fees')) return 'fees';
  if (pathname.startsWith('/admission')) return 'admissions';
  if (pathname.startsWith('/forest-school')) return 'forest-school';
  if (pathname.startsWith('/branches/harrow')) return 'harrow';
  if (pathname.startsWith('/branches/pinner-green')) return 'pinner';
  if (pathname.startsWith('/branches/pinner')) return 'pinner';
  if (pathname.startsWith('/branches/borehamwood')) return 'borehamwood';
  if (pathname.startsWith('/branches/northwood')) return 'northwood';
